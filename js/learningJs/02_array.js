//array

const fruits = ["Apple", "Banana", "Mango"];
console.log(fruits);

console.log(fruits[0]);
console.log(fruits[2]);

//push()

let fruitss = ["Apple", "Banana"];
fruitss.push("Mango");
console.log(fruitss);

//pop()
fruitss.pop();
console.log(fruitss);

//unshift()
fruitss.unshift("Orange");
console.log(fruitss);

//shift()
fruitss.shift();
console.log(fruitss);